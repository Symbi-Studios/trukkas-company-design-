// Job requests posted by forwarders/exporters (see companies.js `posters`).
// A job is the forwarder's booking; the haulage itself runs as one or more
// trips (see trips.js, linked by `jobId`). `trucksRequired` is how many trucks
// the forwarder asked for, so a won job can have 1, 2, 5, 20... trips.
// `status` drives the job lifecycle: Pending (open request) -> Quoted (bid sent)
// -> In Progress (won, trips dispatched/running) -> Completed / Cancelled.
// `budget` and `myBid.amount` are per truck.
function job(entry) {
  return {
    tripType: 'One-way',
    cargoValue: null,
    specialInstructions: '',
    specialNotes: [],
    requirements: ['Truck must be in good condition', 'Valid roadworthiness certificate', 'Real-time tracking required'],
    documents: [],
    paymentTerms: 'On delivery',
    insurance: 'Covered by Exporter',
    trucksRequired: 1,
    featured: false,
    urgent: false,
    saved: false,
    closesInDays: null,
    myBid: null,
    ...entry,
    // Forwarders only attach cargo photos to break-bulk jobs.
    photos: entry.category === 'Break-bulk' ? entry.photos ?? 6 : 0,
  };
}

